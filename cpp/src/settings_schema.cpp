extern "C" const char *astro_settings_schema(void) {
    static std::string out;
    if (!out.empty())
        return out.c_str();
    try {
        const astro::Settings D = astro::Settings::defaults();
        static const char *groups[][3] = {{"camera", "Camera & telescope", "Câmera e telescópio"},
                                          {"detection", "Detection", "Detecção"},
                                          {"plate", "Plate solution", "Solução de placa"},
                                          {"motion", "Motion", "Movimento"},
                                          {"reports", "Reports", "Relatórios"},
                                          {"advanced", "Advanced", "Avançado"}};
        std::ostringstream j;
        j.precision(10);
        j << "{\"groups\":[";
        for (size_t g = 0; g < 6; ++g)
            j << (g ? "," : "") << "{\"id\":" << js(groups[g][0]) << ",\"en\":" << js(groups[g][1]) << ",\"pt\":" << js(groups[g][2])
              << ",\"collapsed\":" << (g == 5 ? "true" : "false") << "}";
        j << "],\"settings\":[";
        bool first = true;
        for (const auto &f : fields()) {
            std::string def = f.def ? f.def : D.str(f.key);
            j << (first ? "" : ",") << "{\"key\":" << js(f.key) << ",\"group\":" << js(f.group) << ",\"type\":" << js(f.type)
              << ",\"en\":" << js(f.en) << ",\"pt\":" << js(f.pt) << ",\"hint_en\":" << js(f.hint_en) << ",\"hint_pt\":" << js(f.hint_pt)
              << ",\"default\":" << js(def.c_str());
            if (std::string(f.type) == "number" || std::string(f.type) == "int")
                j << ",\"min\":" << f.min << ",\"max\":" << f.max;
            if (!f.opts.empty()) {
                j << ",\"options\":[";
                for (size_t i = 0; i < f.opts.size(); ++i)
                    j << (i ? "," : "") << "{\"value\":" << js(f.opts[i].value) << ",\"en\":" << js(f.opts[i].en)
                      << ",\"pt\":" << js(f.opts[i].pt) << "}";
                j << "]";
            }
            j << "}";
            first = false;
        }
        j << "]}";
        out = j.str();
    } catch (...) {
        out = "{\"groups\":[],\"settings\":[]}";
    }
    return out.c_str();
}
